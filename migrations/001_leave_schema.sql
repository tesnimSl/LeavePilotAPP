CREATE TABLE leave_years (
  id BIGSERIAL PRIMARY KEY,
  year INTEGER NOT NULL UNIQUE,
  annual_paid NUMERIC(8,2) NOT NULL DEFAULT 22,
  monthly_paid NUMERIC(8,4) NOT NULL DEFAULT 1.8333,
  annual_sick NUMERIC(8,2) NOT NULL DEFAULT 5,
  initial_paid NUMERIC(10,4) NOT NULL DEFAULT 0,
  initial_sick NUMERIC(10,4) NOT NULL DEFAULT 5,
  sick_carry BOOLEAN NOT NULL DEFAULT FALSE,
  planned_forecast BOOLEAN NOT NULL DEFAULT FALSE,
  day_mode TEXT NOT NULL DEFAULT 'ouvrés',
  start_month INTEGER NOT NULL DEFAULT 1,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
